"""The W8 delivery decisions over the existing route-check messages."""

import pytest

from src.agents.route_planner.checks import classify_issues


@pytest.mark.parametrize(
    ("issue", "tier"),
    [
        ("行程天数不对：要 3 天，实际是第 [1, 2] 天", "hard"),
        ("第1天重复安排了编号 30", "hard"),
        ("第1天「参观馆（停业）」名字带停业字样", "hard"),
        ("第2天「美术馆」16:30 到达，晚于 16:00 停止入场", "hard"),
        ("第2天「美术馆」17:30 离开，晚于 17:00 关门", "hard"),
        ("开放时间冲突：第2天「边门」闭馆", "hard"),
        ("开放时间冲突：第2天「展厅」缺少有效到达时间", "hard"),
        ("第1天餐饮店不当景点：「小面馆」", "hard"),
        ("第1天午饭不是正经吃饭的店", "hard"),
        ("第1天晚饭不是正经吃饭的店", "hard"),
        ("第2天夜景没写到夜景、亮灯或夜游", "hard"),
        ("第2天夜景是 17:20，天还没黑", "hard"),
        ("第2天没有查到路", "hard"),
        ("第2天没有查到路：公园→回住处 自驾", "hard"),
        ("第2天步行 45 分钟，超过 35 分钟：湖边→回住处", "hard"),
        ("第2天没有游览点", "hard"),
        ("第2天缺少午饭", "hard"),
        ("第2天回到住处约 23:16，超过 22:00", "hard"),
        ("第2天没排夜景，回到住处约 24:03，超过 20:30", "hard"),
        ("用户想看夜景，但没有排一个写到夜景的地点", "repair"),
        ("用户喜欢美食，但没有一顿正餐是网友提过的店", "repair"),
        ("用户想去茶馆喝茶，但没有安排茶馆", "repair"),
        ("亲子出行，但没有孩子能玩的地方", "repair"),
        ("必去点「美术馆」没有排上", "repair"),
        ("第2天夜景不是最后一站", "record"),
        ("第2天夜景排在晚饭之前", "record"),
        ("第2天晚饭后只排夜景", "record"),
        ("第2天空等 71 分钟，超过 1 小时：在「花园」", "record"),
        ("第2天有 2 个小吃或补充能量点（面包、酸奶），最多 1 个", "record"),
        ("第2天白天景点 4 个，超过轻松节奏的 3 个", "record"),
        ("第2天夜景 2 个，超过轻松节奏的 1 个", "record"),
        ("第2天游览点 5 个，超过适中节奏的 4 个", "record"),
        ("第2天没有一段至少 60 分钟的歇", "record"),
        ("第2天「没有查到路的画展」约 18:00 结束，超过白天 17:30", "record"),
        ("第2天路上总时间 160 分钟，超过 150 分钟", "record"),
        ("第4天路上总时间 393 分钟，超过远郊上限 360 分钟", "record"),
        ("第2天午饭是 14:00，不在饭点", "record"),
        ("第2天缺少晚饭", "record"),
        ("第2天午饭和晚饭都是锅子：春红火锅、陈记火锅", "record"),
        ("第2天没排夜景，回到住处约 22:47，超过 20:30", "record"),
        ("第2天回到住处约 23:00，超过 22:00", "record"),
    ],
)
def test_shared_issue_tiers(issue, tier):
    assert classify_issues([issue])._asdict() == {
        name: [issue] if name == tier else [] for name in ("hard", "repair", "record")
    }
